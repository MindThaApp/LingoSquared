"""allow content issue reports to reference a PracticeItem, not just an Exercise

`ContentIssueReport.exercise_id` was a hard NOT NULL FK to `exercises`,
but `POST /exercises/{exercise_id}/report` (the only report endpoint
that existed) is what `ReviewPage.tsx` (lexeme-review sessions,
Phase A) and the Endless Practice feed both need to call — and both of
those surfaces are backed entirely by `PracticeItem`, a separate table
with no relationship to `Exercise` at all (confirmed by reading
`app/models/entities.py`: `PracticeItem` has its own `id`, generated by
the practice engine, never an `Exercise` row). `ReviewPage.tsx` was
passing a `PracticeItem.id` into this endpoint and 404ing every time
(reproduced live, see docs/BUILD_LOG.md); the Endless Practice feed had
no report button at all.

Fix: make `exercise_id` nullable and add a nullable `practice_item_id`
FK, mirroring the already-nullable `content_key_id` secondary FK on this
same table. A check constraint enforces exactly one of the two is set
(`num_nonnulls(exercise_id, practice_item_id) = 1`) so every future row
is unambiguous. `POST /practice/items/{item_id}/report` is the new
endpoint for the PracticeItem side (covers review, checkpoint, and
Endless Practice items alike, since all three share the same
PracticeItem table and the same `/practice/items/{id}/answer` grading
endpoint); the existing `POST /exercises/{exercise_id}/report` is
unchanged for real Exercise rows (compiled lesson content).

Additive-only, per the project's established guarded-migration
convention (every migration after 0001 must check existence before
add_column/create_foreign_key/create_check_constraint, since 0001's
`Base.metadata.create_all()` already creates this table in its CURRENT
shape on a genuinely fresh install — see CLAUDE.md's Footguns section).
"""

import sqlalchemy as sa
from alembic import op


revision = "0014"
down_revision = "0013"
branch_labels = None
depends_on = None

_TABLE = "content_issue_reports"


def _column_names(bind, table_name):
    return {col["name"] for col in sa.inspect(bind).get_columns(table_name)}


def _constraint_names(bind, table_name, kind):
    inspector = sa.inspect(bind)
    if kind == "check":
        constraints = inspector.get_check_constraints(table_name)
    elif kind == "foreign_key":
        constraints = inspector.get_foreign_keys(table_name)
    else:
        raise ValueError(f"unsupported constraint kind: {kind}")
    return {constraint.get("name") for constraint in constraints}


def upgrade():
    bind = op.get_bind()

    columns = _column_names(bind, _TABLE)
    if "practice_item_id" not in columns:
        op.add_column(
            _TABLE,
            sa.Column("practice_item_id", sa.String(length=36), nullable=True),
        )

    # Checked by COLUMN, not by this migration's own constraint name: on a
    # genuinely fresh install, 0001's Base.metadata.create_all() already
    # creates this FK (with SQLAlchemy/Postgres's auto-generated
    # "content_issue_reports_practice_item_id_fkey" name, not this one) -
    # checking only the explicit name would create a second, redundant FK
    # on the same column. Same pattern 0005 uses for content_release_id.
    # Re-inspects fresh (rather than reusing an Inspector captured before
    # the add_column above) to see that column's FK state, if any, live.
    practice_item_fk_exists = any(
        fk.get("constrained_columns") == ["practice_item_id"]
        for fk in sa.inspect(bind).get_foreign_keys(_TABLE)
    )
    if not practice_item_fk_exists:
        op.create_foreign_key(
            "fk_content_issue_reports_practice_item_id",
            _TABLE,
            "practice_items",
            ["practice_item_id"],
            ["id"],
            ondelete="RESTRICT",
        )

    exercise_col = next(
        (
            col
            for col in sa.inspect(bind).get_columns(_TABLE)
            if col["name"] == "exercise_id"
        ),
        None,
    )
    if exercise_col is not None and not exercise_col["nullable"]:
        op.alter_column(
            _TABLE,
            "exercise_id",
            existing_type=sa.String(length=36),
            nullable=True,
        )

    check_names = _constraint_names(bind, _TABLE, "check")
    if "ck_content_issue_reports_exactly_one_target" not in check_names:
        op.create_check_constraint(
            "ck_content_issue_reports_exactly_one_target",
            _TABLE,
            "num_nonnulls(exercise_id, practice_item_id) = 1",
        )


def downgrade():
    raise RuntimeError(
        "0014 downgrade is intentionally unsupported: any content issue "
        "report filed against a PracticeItem (review/checkpoint/Endless "
        "Practice) has exercise_id=NULL, which would violate the restored "
        "NOT NULL constraint, and dropping practice_item_id would silently "
        "delete which item those reports pointed at. Restore a verified "
        "pre-upgrade backup instead."
    )
