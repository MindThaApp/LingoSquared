"""Romanized-input nudge ("Right — now write it in script").

A learner who types the Latin romanization of a correct target-script answer is almost
right but NOT correct: grade_answer() returns "almost" and the answer endpoints (see
is_romanized_almost) record the attempt as not correct: no XP, no correct count, no SRS
scheduling. The learner sees NUDGE_MESSAGE (localized client-side via feedback_code) and retries. The romanizations come from a compact backend mirror of the
pronunciation store (backend/app/data/translit/<lang>.json, generated by
`scripts/build_translit.py export-backend`; docs/content/translit/ is the source of truth
and is not shipped in the backend image).

normalize_key() MUST match scripts/translit/common.py::normalize_key (parity is tested).
"""
from __future__ import annotations

import json
import re
import unicodedata
from functools import lru_cache
from pathlib import Path
from typing import Any

NUDGE_MESSAGE = "Right — now write it in script"
# Additive machine-readable marker on answer responses; clients localize the message from it.
NUDGE_CODE = "romanized_input"
TRANSLIT_LANGS = {"ru", "hi", "ar", "fa", "prs"}
DATA_DIR = Path(__file__).resolve().parents[1] / "data" / "translit"

_BIDI = dict.fromkeys(
    [0x200E, 0x200F, 0x061C, 0x202A, 0x202B, 0x202C, 0x202D, 0x202E, 0x2066, 0x2067, 0x2068, 0x2069], None
)
_ARABIC_MARKS = {c: None for c in list(range(0x064B, 0x0653)) + [0x0670, 0x0640]}
_ARABIC_FOLD = {0x064A: "ی", 0x0649: "ی", 0x0643: "ک"}


def normalize_key(text: str, lang: str) -> str:
    t = unicodedata.normalize("NFC", text).translate(_BIDI).replace("*", "")
    if lang in ("ar", "fa", "prs"):
        t = t.translate(_ARABIC_MARKS)
        if lang in ("fa", "prs"):
            t = t.translate(_ARABIC_FOLD)
    return re.sub(r"\s+", " ", t).strip()


@lru_cache(maxsize=8)
def _load(lang: str) -> tuple[dict[str, str], frozenset[str]]:
    p = DATA_DIR / f"{lang}.json"
    if not p.exists():
        return {}, frozenset()
    data = json.loads(p.read_text(encoding="utf-8"))
    return data.get("entries", {}), frozenset(data.get("reviewed", []))


def _entries(lang: str) -> dict[str, str]:
    return _load(lang)[0]


def fold_latin(value: str) -> str:
    """Spelling-insensitive form of a romanization: case, diacritics, hyphens, apostrophes,
    punctuation and spaces never decide a match."""
    t = unicodedata.normalize("NFKD", value.casefold())
    t = "".join(c for c in t if not unicodedata.combining(c))
    return re.sub(r"[^a-z0-9]+", "", t)


def _is_latin(value: str) -> bool:
    letters = [c for c in value if c.isalpha()]
    return bool(letters) and all(ord(c) <= 0x24F or 0x1E00 <= ord(c) <= 0x1EFF for c in letters)


def _strings(correct: Any) -> list[str]:
    if isinstance(correct, str):
        return [correct]
    if isinstance(correct, dict):
        out: list[str] = []
        for v in correct.values():
            out += _strings(v)
        return out
    if isinstance(correct, list):
        out = []
        for v in correct:
            out += _strings(v)
        return out
    return []


def romanized_input_matches(response: Any, correct: Any, language_code: str | None) -> bool:
    """True when `response` is Latin text equal (modulo folding) to the stored romanization of
    a target-script correct answer in `language_code`."""
    if language_code not in TRANSLIT_LANGS or not isinstance(response, str):
        return False
    if not _is_latin(response):
        return False
    wanted = fold_latin(response)
    if not wanted:
        return False
    entries = _entries(language_code)
    if not entries:
        return False
    for answer in _strings(correct):
        if _is_latin(answer):
            continue  # a Latin correct answer is graded normally (e.g. romanize_* exercises)
        if sum(c.isalpha() for c in answer) <= 2:
            continue  # single letters / letter drills: typing the Latin sound is not the skill
        roman = entries.get(normalize_key(answer, language_code))
        if roman and fold_latin(roman) == wanted:
            return True
    return False


def romanized_input_nudge(response: Any, correct: Any, language_code: str | None) -> str | None:
    return NUDGE_MESSAGE if romanized_input_matches(response, correct, language_code) else None


def is_romanized_almost(result: str, response: Any, correct: Any, language_code: str | None) -> bool:
    """True when an "almost" grade came from romanized input: that attempt earns no credit."""
    return result == "almost" and romanized_input_matches(response, correct, language_code)


def feedback_code_for(result: str, response: Any, correct: Any, language_code: str | None) -> str | None:
    return NUDGE_CODE if is_romanized_almost(result, response, correct, language_code) else None


# ---- display lookups (runtime-generated practice prompts, post-answer correct-answer line) ----
# Mirrors scripts/translit/attach.py: additive only, never where it would give the answer away.
_NO_PROMPT_TRANSLIT = {"listen_select", "listen_type", "dictation", "listen_order"}


def lookup(text: Any, lang: str | None) -> tuple[str, bool] | None:
    """(romanization, reviewed) for a target string, or None."""
    if lang not in TRANSLIT_LANGS or not isinstance(text, str):
        return None
    entries, reviewed = _load(lang)
    key = normalize_key(text, lang)
    roman = entries.get(key)
    return (roman, key in reviewed) if roman else None


def correct_answer_translit(correct: Any, lang: str | None) -> str | None:
    """Romanization of the correct answer for the post-answer line. Only for a single
    target-script string answer (Latin answers such as romanize_* exercises, single-letter drills
    and multi-part answers get none). Shown after the answer is revealed, so it leaks nothing."""
    if isinstance(correct, dict) and isinstance(correct.get("canonical"), str):
        correct = correct["canonical"]
    if not isinstance(correct, str) or _is_latin(correct) or sum(c.isalpha() for c in correct) <= 2:
        return None
    hit = lookup(correct, lang)
    return hit[0] if hit else None


def attach_prompt_translit(
    prompt: dict[str, Any], correct: Any, lang: str | None, exercise_type: str, content_key: str | None = None
) -> None:
    """Add `translit` (+ `translit_reviewed`) to target text blocks and `translit_map` (+
    `translit_reviewed_list`) for options / word_bank / pairs of a runtime-generated prompt."""
    if lang not in TRANSLIT_LANGS or not _entries(lang):
        return
    key = (content_key or "").lower()
    if any(m in key for m in ("romaniz", "romanis", "script_ramp", "letter")):
        return  # romanization / letter-sound drills: the romanization IS the answer
    answers = {normalize_key(a, lang) for a in _strings(correct)}

    if exercise_type not in _NO_PROMPT_TRANSLIT:
        for b in prompt.get("text_blocks", []) or []:
            if str(b.get("language_code", "")).split("-")[0] != lang:
                continue
            if normalize_key(str(b.get("text", "")), lang) in answers:
                continue
            if sum(c.isalpha() for c in str(b.get("text", ""))) <= 2:
                continue
            hit = lookup(b.get("text"), lang)
            if hit:
                b["translit"] = hit[0]
                b["translit_reviewed"] = hit[1]

    tmap: dict[str, str] = {}
    reviewed: list[str] = []

    def add(v: Any) -> None:
        if isinstance(v, str) and v not in tmap and sum(c.isalpha() for c in v) > 2:
            hit = lookup(v, lang)
            if hit:
                tmap[v] = hit[0]
                if hit[1]:
                    reviewed.append(v)

    for o in prompt.get("options", []) or []:
        add(o)
    for w in prompt.get("word_bank", []) or []:
        add(w)
    for pr in prompt.get("pairs", []) or []:
        if isinstance(pr, dict):
            add(pr.get("left"))
            add(pr.get("right"))
    if tmap:
        prompt["translit_map"] = tmap
        if reviewed:
            prompt["translit_reviewed_list"] = reviewed
