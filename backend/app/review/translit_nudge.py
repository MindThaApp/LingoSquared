"""Romanized-input nudge ("Right — now write it in script").

A learner who types the Latin romanization of a correct target-script answer is almost
right: grade_answer() returns "almost" (the existing partial-credit path) and the answer
endpoints show NUDGE_MESSAGE. The romanizations come from a compact backend mirror of the
pronunciation store (backend/app/data/translit/<lang>.json, generated by
`scripts/build_translit.py export-backend`; docs/content/translit/ is the source of truth
and is not shipped in the backend image).

normalize_key() MUST match scripts/translit/common.py::normalize_key (parity is tested).
"""
from __future__ import annotations

import json
import re
import unicodedata
from functools import lru_cache
from pathlib import Path
from typing import Any

NUDGE_MESSAGE = "Right — now write it in script"
TRANSLIT_LANGS = {"ru", "hi", "ar", "fa", "prs"}
DATA_DIR = Path(__file__).resolve().parents[1] / "data" / "translit"

_BIDI = dict.fromkeys(
    [0x200E, 0x200F, 0x061C, 0x202A, 0x202B, 0x202C, 0x202D, 0x202E, 0x2066, 0x2067, 0x2068, 0x2069], None
)
_ARABIC_MARKS = {c: None for c in list(range(0x064B, 0x0653)) + [0x0670, 0x0640]}
_ARABIC_FOLD = {0x064A: "ی", 0x0649: "ی", 0x0643: "ک"}


def normalize_key(text: str, lang: str) -> str:
    t = unicodedata.normalize("NFC", text).translate(_BIDI).replace("*", "")
    if lang in ("ar", "fa", "prs"):
        t = t.translate(_ARABIC_MARKS)
        if lang in ("fa", "prs"):
            t = t.translate(_ARABIC_FOLD)
    return re.sub(r"\s+", " ", t).strip()


@lru_cache(maxsize=8)
def _entries(lang: str) -> dict[str, str]:
    p = DATA_DIR / f"{lang}.json"
    if not p.exists():
        return {}
    return json.loads(p.read_text(encoding="utf-8")).get("entries", {})


def fold_latin(value: str) -> str:
    """Spelling-insensitive form of a romanization: case, diacritics, hyphens, apostrophes,
    punctuation and spaces never decide a match."""
    t = unicodedata.normalize("NFKD", value.casefold())
    t = "".join(c for c in t if not unicodedata.combining(c))
    return re.sub(r"[^a-z0-9]+", "", t)


def _is_latin(value: str) -> bool:
    letters = [c for c in value if c.isalpha()]
    return bool(letters) and all(ord(c) <= 0x24F or 0x1E00 <= ord(c) <= 0x1EFF for c in letters)


def _strings(correct: Any) -> list[str]:
    if isinstance(correct, str):
        return [correct]
    if isinstance(correct, dict):
        out: list[str] = []
        for v in correct.values():
            out += _strings(v)
        return out
    if isinstance(correct, list):
        out = []
        for v in correct:
            out += _strings(v)
        return out
    return []


def romanized_input_matches(response: Any, correct: Any, language_code: str | None) -> bool:
    """True when `response` is Latin text equal (modulo folding) to the stored romanization of
    a target-script correct answer in `language_code`."""
    if language_code not in TRANSLIT_LANGS or not isinstance(response, str):
        return False
    if not _is_latin(response):
        return False
    wanted = fold_latin(response)
    if not wanted:
        return False
    entries = _entries(language_code)
    if not entries:
        return False
    for answer in _strings(correct):
        if _is_latin(answer):
            continue  # a Latin correct answer is graded normally (e.g. romanize_* exercises)
        if sum(c.isalpha() for c in answer) <= 2:
            continue  # single letters / letter drills: typing the Latin sound is not the skill
        roman = entries.get(normalize_key(answer, language_code))
        if roman and fold_latin(roman) == wanted:
            return True
    return False


def romanized_input_nudge(response: Any, correct: Any, language_code: str | None) -> str | None:
    return NUDGE_MESSAGE if romanized_input_matches(response, correct, language_code) else None
